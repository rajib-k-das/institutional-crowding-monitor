"""
Check that DuckDB and Snowflake produce the same results from the same SEC data: row counts and headline numbers
from every mart, computed on both warehouses and compared. Writes docs/snowflake/parity.md.

Run after building both (dbt build, and dbt build --target snowflake):
    python scripts/compare_engines.py
"""

from __future__ import annotations

import datetime as dt
import math
import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ingest"))
from load_snowflake import connect  # noqa: E402

OUT = ROOT / "docs" / "snowflake" / "parity.md"

# Plain SQL that runs unchanged on both warehouses.
CHECKS = [
    ("Report quarters", "select count(*) from marts.fct_disclosure_quarter"),
    ("Manager-quarters (final)", "select sum(managers_final) from marts.fct_disclosure_quarter"),
    ("Manager-quarters known at the deadline", "select sum(managers_known_at_deadline) from marts.fct_disclosure_quarter"),
    ("Value reported, final ($ trillion, all quarters)", "select sum(value_usd_final) / 1e12 from marts.fct_disclosure_quarter"),
    ("Value missed by a naive total ($ trillion)", "select sum(value_usd_missed_by_naive_total) / 1e12 from marts.fct_disclosure_quarter"),
    ("Original filings in thousands", "select sum(original_filings_in_thousands) from marts.fct_disclosure_quarter"),
    ("Original filings with swapped columns", "select sum(original_filings_swapped) from marts.fct_disclosure_quarter"),
    ("Managers (dim_manager)", "select count(*) from marts.dim_manager"),
    ("Securities (dim_security)", "select count(*) from marts.dim_security"),
    ("Manager-quarter rows", "select count(*) from marts.fct_manager_quarter"),
    ("Median share of portfolio changed by next report",
     "select median(pct_value_changed_by_next_quarter) from marts.fct_manager_quarter"),
    ("Security-quarter rows", "select count(*) from marts.fct_security_quarter"),
    ("Holder positions (final, all quarters)", "select sum(holders_final) from marts.fct_security_quarter"),
    ("Crowding decile rows", "select count(*) from marts.fct_crowding_deciles"),
    ("Decile 10 minus 1, after data public (avg per quarter)",
     "select avg(case when crowding_decile = 10 then avg_return_following_quarter end)"
     " - avg(case when crowding_decile = 1 then avg_return_following_quarter end) from marts.fct_crowding_deciles"),
    ("Breadth streaks (3+ rising quarters)", "select count(*) from marts.fct_breadth_streaks"),
    ("Streaks followed by a fall in holders",
     "select sum(case when reversed_after then 1 else 0 end) from marts.fct_breadth_streaks"),
]


def run(execute) -> list[float | None]:
    values = []
    for _, sql in CHECKS:
        value = execute(sql)
        values.append(None if value is None else float(value))
    return values


def same(a: float | None, b: float | None) -> bool:
    if a is None or b is None:
        return a is None and b is None
    return math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-9)


def fmt(v: float | None) -> str:
    if v is None:
        return "null"
    return f"{v:,.0f}" if v == int(v) else f"{v:,.6f}"


def main() -> None:
    with duckdb.connect(str(ROOT / "data" / "warehouse.duckdb"), read_only=True) as con:
        local = run(lambda sql: con.execute(sql).fetchone()[0])
    with connect("CROWDING") as sf:
        cur = sf.cursor()
        cur.execute("alter session set query_tag = 'crowding:parity'")
        remote = run(lambda sql: cur.execute(sql).fetchone()[0])

    rows = [(name, fmt(a), fmt(b), "✅" if same(a, b) else "❌") for (name, _), a, b in zip(CHECKS, local, remote)]
    matched = sum(r[3] == "✅" for r in rows)
    lines = [
        "# DuckDB vs Snowflake: same data, same answers",
        "",
        f"Generated by `scripts/compare_engines.py` on {dt.date.today():%d %b %Y}. Both warehouses were built from the "
        "same SEC data sets with the same dbt models; each number below is computed separately on each.",
        "",
        f"**{matched} of {len(rows)} checks match** (relative tolerance 1e-9).",
        "",
        "| Check | DuckDB | Snowflake | Match |",
        "|---|---:|---:|:---:|",
        *[f"| {n} | {a} | {b} | {m} |" for n, a, b, m in rows],
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    if matched != len(rows):
        sys.exit("Some checks differ: see the table above.")


if __name__ == "__main__":
    main()
